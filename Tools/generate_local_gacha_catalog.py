"""Build three permanent banners and matching client/server pools."""
import json, math, struct, zlib
from collections import Counter
from fractions import Fraction
import UnityPy
from read_plain_table import read_table, write_table, root
DB_HASH='30FF13B981773B83827E17DB9C456368'
# Native base-UR festival releases use ordinary coins. PvP reward Varghese is excluded.
UR_FESTIVAL_BASES={323501,323901,324701,324801,325101,325201,326001,326201,326501,327101,327601,327801,328401,328501,328901,329501,330301,330401}

def generate():
 banners=read_table('DB_gamble_display','DBGambleDisplayRow')
 skins=read_table('DB_skin_base','DBSkinBaseRow')
 original_pool=read_table('DB_gamble_group','DBGambleGroupRow')
 coins={i['item_id']:i for i in json.loads((root/'Research/DecodedCache/items.json').read_text())}
 heroes={(h['id']^0x92929292)&0xffffffff:h for h in read_table('DB_hero_base','DBHeroBaseRow')}
 canonical={}
 for s in skins:
  h=s['matching_hero_id']
  if h>0 and(h not in canonical or (s['rating'],s['id'])<(canonical[h]['rating'],canonical[h]['id'])):canonical[h]=s
 pools={108:[],1309:[],120:[]}
 for h,s in sorted(canonical.items()):
  coin=coins.get(s['hero_coin'],{});category=heroes[h]['hero_category']
  group=1309 if category.startswith('Collabo_') or coin.get('item_type')==27 else 108 if coin.get('item_type')==28 or s['id'] in UR_FESTIVAL_BASES else 120
  pools[group].append(s)
 assert sum(map(len,pools.values()))==len(canonical) and all(pools.values())
 assert 372001 in {s['id'] for s in pools[108]}
 assert 329701 in {s['id'] for s in pools[1309]}
 assert 325701 in {s['id'] for s in pools[120]}
 filler=[s for s in pools[120] if s["rating"]<5]
 for group in (108,1309):
  existing={s["id"] for s in pools[group]};pools[group]+=[s for s in filler if s["id"] not in existing]
 chosen=[]
 for bid in (65,109,20):
  b=dict(next(b for b in banners if b['id']==bid))
  # Ordinary draw controls avoid stale wish/bonus/mileage event dependencies.
  b.update(gamble_type=1,gamble_pickup=0,probability_check=0,probability=0,gamble_control=3,
   gamble_bonus_rule_type=0,list_array_gacha_bonus_reward_group=[],list_array_pickup_skin_id=[],
   fail_bonus_check=0,hero_gacha_fail_count=0,gacha_bonus_count_reset=0,hero_gacha_fail_group=0,
   gamble_limit_count=0,account_running_time=0,gamble_information_detail_onoff=0,
   daily_free_chance=0,free_chance=0,event_gacha_start='2020-01-01 00:00:00',
   event_gacha_end='9999-12-31 23:59:59',special_gamble_bg='')
  for n in range(1,5):
   active=n<=2;count=(1 if n==1 else 11) if active else 0;cost=(3 if n==1 else 30) if active else 0
   b.update({f'gamble_count_{n}':count,f'gamble_money_id_{n}':500011 if active else 0,
    f'gamble_money_count_{n}':cost,f'gamble_reward_id_{n}':500012 if active else 0,
    f'gamble_reward_id_count_{n}':count*1000,f'gamble_mileage_{n}':0})
  chosen.append(b)
 client_entries=[];server_entries=[];rating_rows=[];report=[]
 for b in chosen:
  group=b['gamble_group'];pool=pools[group];counts=Counter(min(s['rating'],5) for s in pool)
  baseline=next(r for r in read_table('DB_gamble_rating_per','DBGambleRatingPerRow') if r['gamble_group']==group)
  # Native UI returns integer percentage points. Round the requested ~2.5x boost.
  ssr=(baseline['rating_5']*5+1)//2
  lower=baseline['rating_3']+baseline['rating_4'];remaining=100-ssr
  r=(remaining*baseline['rating_3']+lower//2)//lower
  percentages={3:r,4:remaining-r,5:ssr}
  assert all(counts[r] for r in percentages)
  rating_rows.append(dict(id=b['id'],gamble_group=group,**{f'rating_{r}':percentages.get(r,0) for r in range(1,6)}))
  odds=[Fraction(percentages[min(s['rating'],5)],100*counts[min(s['rating'],5)]) for s in pool]
  denominator=math.lcm(*(x.denominator for x in odds))
  for s,c in zip(pool,odds):
   p=dict(id=900000+len(client_entries),gamble_group=group,skin_id=s['id'],gamble_rate=1000,pick_up_check=0,skin_level=1,skin_awaken=0)
   client_entries.append(p);server_entries.append(dict(p,gamble_rate=int(c*denominator)))
  assert sum(odds)==1
  report.append(dict(banner=b['id'],group=group,count=len(pool),artwork=b['gamble_BG_name'],rarity_percentages=percentages,
   units=[dict(id=s['id'],hero=s['matching_hero_id'],portrait=s['skin_portrait_base'],rate_percent=float(c*100)) for s,c in zip(pool,odds)]))
 out=['#pragma once','// Generated by Tools/generate_local_gacha_catalog.py.','namespace GcLocal {',
  'struct Banner { int id; int group; int single; int multiple; };','inline const Banner Banners[] = {']
 out+=['{%d,%d,%d,%d},'%(b['id'],b['gamble_group'],b['gamble_count_1'],b['gamble_count_2']) for b in chosen]
 out+=['};','struct Skin { int id; int hero; int rating; };','inline const Skin Skins[] = {']
 out+=['{%d,%d,%d},'%(s['id'],s['matching_hero_id'],s['rating']) for s in skins]
 out+=['};','struct PoolEntry { int group; int skin; int weight; int level; int awaken; };','inline const PoolEntry Pool[] = {']
 out+=['{%d,%d,%d,%d,%d},'%(p['gamble_group'],p['skin_id'],p['gamble_rate'],p['skin_level'],p['skin_awaken']) for p in server_entries]
 out+=['};','}'];(root/'Server/Protocol/LocalGachaCatalog.h').write_text('\n'.join(out)+'\n')
 modified={
 'DB_gamble_display':('DBGambleDisplayRow',chosen),
 'DB_gamble_group':('DBGambleGroupRow',[p for p in original_pool if p['gamble_group'] not in pools]+client_entries),
 'DB_gamble_rating_per':('DBGambleRatingPerRow',[p for p in read_table('DB_gamble_rating_per','DBGambleRatingPerRow') if p['gamble_group'] not in pools]+rating_rows)}
 from expand_coin_shop import normal_shop
 normal_units=next(r['units'] for r in report if r['banner']==20)
 normal_ids={s['id'] for s in pools[120]}
 modified['DB_coin_shop']=('DBCoinShopRow',normal_shop(normal_units,[s for s in pools[108] if s['id'] not in normal_ids],[s for s in pools[1309] if s['id'] not in normal_ids]))
 for name,(cls,_) in modified.items():assert write_table(read_table(name,cls),cls)==(root/f'Research/DecodedCache/{name}.bin').read_bytes()
 env=UnityPy.load(str(root/'Research/DecodedCache'/DB_HASH));changed=set()
 for o in env.objects:
  if o.type.name!='TextAsset':continue
  a=o.read()
  if a.m_Name in modified:
   cls,rows=modified[a.m_Name];a.m_Script=write_table(rows,cls).decode('utf8','surrogateescape');a.save();changed.add(a.m_Name)
 assert changed==set(modified)
 target=root/'dist/cache/b'/DB_HASH;target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(env.file.save(packer='lz4'))
 checked=UnityPy.load(str(target));saved={o.read().m_Name:o.read().m_Script for o in checked.objects if o.type.name=='TextAsset'}
 for name,(cls,rows) in modified.items():assert saved[name].encode('utf8','surrogateescape')==write_table(rows,cls)
 # BM passes this per-bundle CRC into Unity. Keep integrity checking enabled
 # and update only the modified database's manifest entry.
 manifest=bytearray((root/'Research/DecodedCache/br-b.bin').read_bytes())
 assert manifest.find(DB_HASH.encode())==27
 original=UnityPy.load(str(root/'Research/DecodedCache'/DB_HASH))
 original_crc=zlib.crc32(b''.join(f.save() for f in original.file.files.values()))
 assert struct.unpack_from('<I',manifest,12)[0]==original_crc
 new_crc=zlib.crc32(b''.join(f.save() for f in checked.file.files.values()))
 struct.pack_into('<I',manifest,12,new_crc)
 (root/'dist/cache/br-b.bin').write_bytes(manifest)
 (root/'dist/three-banner-pools.json').write_text(json.dumps(report,indent=2))
 print('Three permanent banners:',[(r['banner'],r['group'],r['count']) for r in report]);print('Verified client DB:',target)
if __name__=='__main__':
 generate()
 import runpy
